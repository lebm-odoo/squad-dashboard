export type Locale = 'fr' | 'en';

const stored = (() => {
  try {
    return localStorage.getItem('sd-locale');
  } catch {
    return null;
  }
})();

export const i18n = $state<{ locale: Locale }>({
  locale: stored === 'fr' ? 'fr' : 'en',
});

export function setLocale(locale: Locale) {
  i18n.locale = locale;
  document.documentElement.lang = locale;
  try {
    localStorage.setItem('sd-locale', locale);
  } catch {
    // a private window keeps the choice for the visit
  }
}

